-- ============================================================
-- Pagila – schéma snehovej vločky pre dátový sklad (PostgreSQL)
-- Grain: 1 riadok fact_rental = 1 výpožička jednej kópie filmu
--         jedným zákazníkom, obsluhovaná jedným zamestnancom.
--
-- Snehová vločka:
--   fact_rental
--     ├── dim_date (rental_date_key, return_date_key – role-playing)
--     ├── dim_customer ──> dim_address ──> dim_city ──> dim_country
--     ├── dim_staff    ──> dim_store ──> dim_address ──> dim_city ──> dim_country
--     └── dim_inventory ──> dim_film ──> dim_language
--                        └─> dim_store ──> dim_address ──> dim_city ──> dim_country
--
--   bridge_film_category rieši M:N vzťah film – kategória.
-- ============================================================
CREATE SCHEMA IF NOT EXISTS dwh_pagila_snowflake;
SET search_path TO dwh_pagila_snowflake;

-- ------------------------------------------------------------
-- Geografické dimenzie (normalizovaná hierarchia)
-- ------------------------------------------------------------
CREATE TABLE dim_country (
    country_key     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id      INTEGER      NOT NULL UNIQUE,
    country         TEXT         NOT NULL
);

CREATE TABLE dim_city (
    city_key        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id         INTEGER      NOT NULL UNIQUE,
    city            TEXT         NOT NULL,
    country_key     BIGINT       NOT NULL REFERENCES dim_country(country_key)
);

CREATE TABLE dim_address (
    address_key     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_id      INTEGER      NOT NULL UNIQUE,
    address         TEXT         NOT NULL,
    address2        TEXT,
    district        TEXT,
    postal_code     TEXT,
    phone           TEXT,
    city_key        BIGINT       NOT NULL REFERENCES dim_city(city_key)
);

-- ------------------------------------------------------------
-- Časová dimenzia
-- ------------------------------------------------------------
CREATE TABLE dim_date (
    date_key        INTEGER      PRIMARY KEY,           -- napr. 20260131
    full_date       DATE         NOT NULL UNIQUE,
    day             SMALLINT     NOT NULL CHECK (day BETWEEN 1 AND 31),
    month           SMALLINT     NOT NULL CHECK (month BETWEEN 1 AND 12),
    month_name      TEXT         NOT NULL,
    quarter         SMALLINT     NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year            SMALLINT     NOT NULL,
    weekday         TEXT         NOT NULL,
    is_weekend      BOOLEAN      NOT NULL DEFAULT FALSE
);

-- ------------------------------------------------------------
-- Jazyk a kategória filmu
-- ------------------------------------------------------------
CREATE TABLE dim_language (
    language_key    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language_id     INTEGER      NOT NULL UNIQUE,
    name            TEXT         NOT NULL
);

CREATE TABLE dim_category (
    category_key    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     INTEGER      NOT NULL UNIQUE,
    name            TEXT         NOT NULL
);

-- ------------------------------------------------------------
-- Obchod a zamestnanec
-- Poznámka: manager_staff_id je zámerne obyčajný atribút, nie FK,
-- aby medzi dim_store a dim_staff nevznikol cyklus.
-- ------------------------------------------------------------
CREATE TABLE dim_store (
    store_key       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        INTEGER      NOT NULL UNIQUE,
    manager_staff_id INTEGER,
    address_key     BIGINT       NOT NULL REFERENCES dim_address(address_key)
);

CREATE TABLE dim_staff (
    staff_key       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id        INTEGER      NOT NULL UNIQUE,
    first_name      TEXT         NOT NULL,
    last_name       TEXT         NOT NULL,
    email           TEXT,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    username        TEXT,
    store_key       BIGINT       NOT NULL REFERENCES dim_store(store_key)
);

-- ------------------------------------------------------------
-- Zákazník
-- ------------------------------------------------------------
CREATE TABLE dim_customer (
    customer_key    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     INTEGER      NOT NULL UNIQUE,
    first_name      TEXT         NOT NULL,
    last_name       TEXT         NOT NULL,
    email           TEXT,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    create_date     DATE,
    address_key     BIGINT       NOT NULL REFERENCES dim_address(address_key)
);

-- ------------------------------------------------------------
-- Film a jeho väzba na kategórie (M:N)
-- ------------------------------------------------------------
CREATE TABLE dim_film (
    film_key        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    film_id         INTEGER      NOT NULL UNIQUE,
    title           TEXT         NOT NULL,
    description     TEXT,
    release_year    INTEGER,
    rental_duration SMALLINT     NOT NULL CHECK (rental_duration >= 0),
    rental_rate     NUMERIC(4,2) NOT NULL CHECK (rental_rate >= 0),
    length          SMALLINT     CHECK (length IS NULL OR length >= 0),
    replacement_cost NUMERIC(5,2) NOT NULL CHECK (replacement_cost >= 0),
    rating          TEXT,
    special_features TEXT,
    language_key    BIGINT       NOT NULL REFERENCES dim_language(language_key),
    original_language_key BIGINT REFERENCES dim_language(language_key)
);

CREATE TABLE bridge_film_category (
    film_key        BIGINT       NOT NULL REFERENCES dim_film(film_key),
    category_key    BIGINT       NOT NULL REFERENCES dim_category(category_key),
    PRIMARY KEY (film_key, category_key)
);

-- ------------------------------------------------------------
-- Kópia filmu v konkrétnom obchode
-- ------------------------------------------------------------
CREATE TABLE dim_inventory (
    inventory_key   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id    INTEGER      NOT NULL UNIQUE,
    film_key        BIGINT       NOT NULL REFERENCES dim_film(film_key),
    store_key       BIGINT       NOT NULL REFERENCES dim_store(store_key)
);

-- ------------------------------------------------------------
-- Faktová tabuľka
-- ------------------------------------------------------------
CREATE TABLE fact_rental (
    rental_key      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_id       INTEGER      NOT NULL UNIQUE,       -- degenerovaný kľúč výpožičky
    rental_date_key INTEGER      NOT NULL REFERENCES dim_date(date_key),
    return_date_key INTEGER      REFERENCES dim_date(date_key),
    customer_key    BIGINT       NOT NULL REFERENCES dim_customer(customer_key),
    staff_key       BIGINT       NOT NULL REFERENCES dim_staff(staff_key),
    inventory_key   BIGINT       NOT NULL REFERENCES dim_inventory(inventory_key),
    rental_fee      NUMERIC(6,2) NOT NULL CHECK (rental_fee >= 0),
    rental_days     INTEGER      NOT NULL DEFAULT 0 CHECK (rental_days >= 0),
    late_days       INTEGER      NOT NULL DEFAULT 0 CHECK (late_days >= 0),
    late_fee        NUMERIC(8,2) NOT NULL DEFAULT 0 CHECK (late_fee >= 0),
    rental_count    INTEGER      NOT NULL DEFAULT 1 CHECK (rental_count > 0),
    is_returned     BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_fact_rental_rental_date ON fact_rental(rental_date_key);
CREATE INDEX idx_fact_rental_return_date ON fact_rental(return_date_key);
CREATE INDEX idx_fact_rental_customer    ON fact_rental(customer_key);
CREATE INDEX idx_fact_rental_staff       ON fact_rental(staff_key);
CREATE INDEX idx_fact_rental_inventory   ON fact_rental(inventory_key);

CREATE INDEX idx_dim_customer_address    ON dim_customer(address_key);
CREATE INDEX idx_dim_staff_store         ON dim_staff(store_key);
CREATE INDEX idx_dim_inventory_film      ON dim_inventory(film_key);
CREATE INDEX idx_dim_inventory_store     ON dim_inventory(store_key);
