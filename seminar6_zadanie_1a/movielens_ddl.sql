-- ============================================================
-- MovieLens – hviezdicová schéma pre dátový sklad (PostgreSQL)
-- Grain: 1 riadok fact_rating = 1 hodnotenie filmu používateľom
-- ============================================================
CREATE SCHEMA IF NOT EXISTS dwh_movielens;
SET search_path TO dwh_movielens;

-- Časová dimenzia: 1 riadok = 1 kalendárny deň
CREATE TABLE dim_date (
    date_key        INTEGER      PRIMARY KEY,          -- napr. 20260131
    full_date       DATE         NOT NULL UNIQUE,
    day             SMALLINT     NOT NULL CHECK (day BETWEEN 1 AND 31),
    month           SMALLINT     NOT NULL CHECK (month BETWEEN 1 AND 12),
    quarter         SMALLINT     NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year            SMALLINT     NOT NULL,
    weekday         TEXT         NOT NULL,
    is_weekend      BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Používateľská dimenzia (demografia + povolanie)
CREATE TABLE dim_user (
    user_key        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER      NOT NULL UNIQUE,      -- prirodzený kľúč zo zdroja
    gender          CHAR(1),
    age             SMALLINT,
    age_group       TEXT,
    occupation      TEXT,
    zip_code        TEXT
);

-- Filmová dimenzia (základné atribúty filmu)
CREATE TABLE dim_movie (
    movie_key       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movie_id        INTEGER      NOT NULL UNIQUE,      -- prirodzený kľúč zo zdroja
    title           TEXT         NOT NULL,
    release_year    SMALLINT,
    genre_list      TEXT,                              -- čitateľný zoznam žánrov
    movie_url       TEXT
);

-- Žáner ako samostatná dimenzia (multi-valued atribút filmu)
CREATE TABLE dim_genre (
    genre_key       INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_name      TEXT         NOT NULL UNIQUE
);

-- Bridge tabuľka pre M:N vzťah film – žáner
CREATE TABLE bridge_movie_genre (
    movie_key       BIGINT       NOT NULL REFERENCES dim_movie(movie_key) ON DELETE CASCADE,
    genre_key       INTEGER      NOT NULL REFERENCES dim_genre(genre_key) ON DELETE CASCADE,
    PRIMARY KEY (movie_key, genre_key)
);

-- Faktová tabuľka hodnotení
CREATE TABLE fact_rating (
    rating_key      BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_key        INTEGER      NOT NULL REFERENCES dim_date(date_key),
    user_key        BIGINT       NOT NULL REFERENCES dim_user(user_key),
    movie_key       BIGINT       NOT NULL REFERENCES dim_movie(movie_key),
    rating          NUMERIC(2,1) NOT NULL CHECK (rating BETWEEN 0.5 AND 5.0),
    rating_count    INTEGER      NOT NULL DEFAULT 1 CHECK (rating_count = 1),
    rated_at        TIMESTAMP    NOT NULL,             -- pôvodný timestamp (degenerovaný atribút)
    CONSTRAINT uq_fact_rating UNIQUE (user_key, movie_key, rated_at)
);

CREATE INDEX idx_fact_rating_date   ON fact_rating(date_key);
CREATE INDEX idx_fact_rating_user   ON fact_rating(user_key);
CREATE INDEX idx_fact_rating_movie  ON fact_rating(movie_key);

-- Voliteľná dimenzia tagov a bridge pre analýzu tagov
CREATE TABLE dim_tag (
    tag_key         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tag_name        TEXT         NOT NULL UNIQUE
);

CREATE TABLE bridge_movie_tag (
    movie_key       BIGINT       NOT NULL REFERENCES dim_movie(movie_key) ON DELETE CASCADE,
    tag_key         INTEGER      NOT NULL REFERENCES dim_tag(tag_key) ON DELETE CASCADE,
    PRIMARY KEY (movie_key, tag_key)
);
