-- ============================================================
-- Chinook – hviezdicová schéma pre dátový sklad (PostgreSQL)
-- Grain: 1 riadok fact_invoice_line = 1 položka faktúry
-- ============================================================
CREATE SCHEMA IF NOT EXISTS dwh_chinook;
SET search_path TO dwh_chinook;

CREATE TABLE dim_date (
    date_key        INTEGER      PRIMARY KEY,          -- napr. 20260131
    full_date       DATE         NOT NULL UNIQUE,
    day             SMALLINT     NOT NULL CHECK (day BETWEEN 1 AND 31),
    month           SMALLINT     NOT NULL CHECK (month BETWEEN 1 AND 12),
    quarter         SMALLINT     NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year            SMALLINT     NOT NULL,
    weekday         TEXT         NOT NULL,
    is_weekend      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE dim_customer (
    customer_key    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     INTEGER      NOT NULL UNIQUE,
    first_name      TEXT,
    last_name       TEXT,
    company         TEXT,
    address         TEXT,
    city            TEXT,
    state           TEXT,
    country         TEXT,
    postal_code     TEXT,
    phone           TEXT,
    email           TEXT
);

-- Dimenzia track: album, interpret, žáner a médium sú denormalizované
CREATE TABLE dim_track (
    track_key       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    track_id        INTEGER      NOT NULL UNIQUE,
    track_name      TEXT         NOT NULL,
    album_title     TEXT,
    artist_name     TEXT,
    genre_name      TEXT,
    media_type      TEXT,
    composer        TEXT,
    duration_ms     INTEGER,
    unit_price      NUMERIC(10,2)
);

CREATE TABLE dim_employee (
    employee_key    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INTEGER      NOT NULL UNIQUE,
    full_name       TEXT         NOT NULL,
    title           TEXT,
    reports_to      TEXT,
    city            TEXT,
    country         TEXT,
    hire_date       DATE
);

CREATE TABLE fact_invoice_line (
    invoice_line_key BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id       INTEGER     NOT NULL,             -- degenerovaný kľúč faktúry
    date_key         INTEGER     NOT NULL REFERENCES dim_date(date_key),
    customer_key     BIGINT      NOT NULL REFERENCES dim_customer(customer_key),
    track_key        BIGINT      NOT NULL REFERENCES dim_track(track_key),
    employee_key     BIGINT      REFERENCES dim_employee(employee_key),
    quantity         INTEGER     NOT NULL CHECK (quantity > 0),
    unit_price       NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    line_amount      NUMERIC(12,2) NOT NULL CHECK (line_amount >= 0)
);

CREATE INDEX idx_fact_invoice_line_date     ON fact_invoice_line(date_key);
CREATE INDEX idx_fact_invoice_line_customer ON fact_invoice_line(customer_key);
CREATE INDEX idx_fact_invoice_line_track    ON fact_invoice_line(track_key);
CREATE INDEX idx_fact_invoice_line_employee ON fact_invoice_line(employee_key);
