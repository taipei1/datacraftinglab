-- ============================================================
-- Northwind – hviezdicová schéma pre dátový sklad (PostgreSQL)
-- Grain: 1 riadok fact_order_line = 1 položka objednávky
-- ============================================================
CREATE SCHEMA IF NOT EXISTS dwh_northwind;
SET search_path TO dwh_northwind;

CREATE TABLE dim_date (
    date_key        INTEGER      PRIMARY KEY,          -- napr. 20260131
    full_date       DATE         NOT NULL UNIQUE,
    day             SMALLINT     NOT NULL CHECK (day BETWEEN 1 AND 31),
    month           SMALLINT     NOT NULL CHECK (month BETWEEN 1 AND 12),
    quarter         SMALLINT     NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year            SMALLINT     NOT NULL,
    weekday         TEXT         NOT NULL,
    is_weekend      BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE dim_customer (
    customer_key    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     TEXT         NOT NULL UNIQUE,      -- Northwind používa 5-znakové ID
    company_name    TEXT,
    contact_name    TEXT,
    contact_title   TEXT,
    city            TEXT,
    region          TEXT,
    country         TEXT,
    postal_code     TEXT
);

-- Kategória a dodávateľ sú denormalizované pre jednoduchú hviezdu
CREATE TABLE dim_product (
    product_key     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      INTEGER      NOT NULL UNIQUE,
    product_name    TEXT         NOT NULL,
    category_name   TEXT,
    supplier_name   TEXT,
    quantity_per_unit TEXT,
    unit_price      NUMERIC(10,2),
    discontinued    BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE dim_employee (
    employee_key    BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     INTEGER      NOT NULL UNIQUE,
    full_name       TEXT         NOT NULL,
    title           TEXT,
    city            TEXT,
    country         TEXT,
    hire_date       DATE
);

CREATE TABLE dim_shipper (
    shipper_key     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipper_id      INTEGER      NOT NULL UNIQUE,
    company_name    TEXT         NOT NULL
);

CREATE TABLE fact_order_line (
    order_line_key  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        INTEGER      NOT NULL,             -- degenerovaný kľúč objednávky
    date_key        INTEGER      NOT NULL REFERENCES dim_date(date_key),
    customer_key    BIGINT       NOT NULL REFERENCES dim_customer(customer_key),
    product_key     BIGINT       NOT NULL REFERENCES dim_product(product_key),
    employee_key    BIGINT       REFERENCES dim_employee(employee_key),
    shipper_key     BIGINT       REFERENCES dim_shipper(shipper_key),
    quantity        INTEGER      NOT NULL CHECK (quantity > 0),
    unit_price      NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    discount        NUMERIC(4,2) NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 1),
    line_amount     NUMERIC(12,2) NOT NULL CHECK (line_amount >= 0),
    CONSTRAINT uq_fact_order_line UNIQUE (order_id, product_key)
);

CREATE INDEX idx_fact_order_line_date     ON fact_order_line(date_key);
CREATE INDEX idx_fact_order_line_customer ON fact_order_line(customer_key);
CREATE INDEX idx_fact_order_line_product  ON fact_order_line(product_key);
CREATE INDEX idx_fact_order_line_employee ON fact_order_line(employee_key);
CREATE INDEX idx_fact_order_line_shipper  ON fact_order_line(shipper_key);
